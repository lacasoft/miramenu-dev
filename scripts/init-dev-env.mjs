// Creates the root .env for local development and CI, with random secrets for the local
// containers. It never prints the values. Production configuration comes from the
// platform, not from here.
//   node scripts/init-dev-env.mjs           create .env if it does not exist
//   node scripts/init-dev-env.mjs --update  append only the variables .env is missing
//   node scripts/init-dev-env.mjs --force   replace .env with new secrets
import { randomBytes } from 'node:crypto';
import { appendFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const envPath = join(dirname(fileURLToPath(import.meta.url)), '..', '.env');
const mode = process.argv.includes('--force') ? 'force' : process.argv.includes('--update') ? 'update' : 'create';

const secret = () => randomBytes(24).toString('base64url');
const contexts = ['business_access', 'catalog', 'diners', 'interactions', 'measurement'];
const ports = { api: 3000, postgres: 55432, redis: 56379, s3: 58333, smtp: 51025, mailpitUi: 58025, twilio: 58040 };

/** Every variable in order, with the value it gets when it is first written. */
const variables = [
  ['PORT', () => String(ports.api)],
  ['CORS_ALLOWED_ORIGINS', () => ''],
  ['PUBLIC_SITE_URL', () => 'http://miramenu.localhost:5173'],
  ['ADMIN_APP_URL', () => 'http://admin.miramenu.localhost:5174'],
  ['POSTGRES_SUPERUSER_PASSWORD', secret],
  ['DB_HOST', () => '127.0.0.1'],
  ['DB_PORT', () => String(ports.postgres)],
  ['DB_NAME', () => 'miramenu'],
  ['DB_TEST_NAME', () => 'miramenu_test'],
  ['DB_MIGRATOR_USER', () => 'miramenu_migrator'],
  ['DB_MIGRATOR_PASSWORD', secret],
  ...contexts.flatMap((context) => [
    [`DB_${context.toUpperCase()}_USER`, () => `miramenu_${context}`],
    [`DB_${context.toUpperCase()}_PASSWORD`, secret],
  ]),
  ['REDIS_HOST', () => '127.0.0.1'],
  ['REDIS_PORT', () => String(ports.redis)],
  ['REDIS_PASSWORD', secret],
  ['S3_PORT', () => String(ports.s3)],
  ['S3_ENDPOINT', () => `http://127.0.0.1:${ports.s3}`],
  ['S3_REGION', () => 'us-east-1'],
  ['S3_BUCKET', () => 'media'],
  ['S3_ORIGINALS_BUCKET', () => 'media-originals'],
  ['S3_ACCESS_KEY_ID', () => randomBytes(12).toString('hex')],
  ['S3_SECRET_ACCESS_KEY', secret],
  ['S3_FORCE_PATH_STYLE', () => 'true'],
  ['MEDIA_PUBLIC_BASE_URL', () => `http://127.0.0.1:${ports.s3}/media`],
  ['SMTP_HOST', () => '127.0.0.1'],
  ['SMTP_PORT', () => String(ports.smtp)],
  ['SMTP_FROM', () => '"Miramenu <no-reply@miramenu.localhost>"'],
  ['MAILPIT_UI_PORT', () => String(ports.mailpitUi)],
  // Codes go to the local Twilio simulator (compose.yaml), never to Twilio.
  ['VERIFICATION_CHANNEL', () => 'whatsapp'],
  ['TWILIO_SIMULATOR_PORT', () => String(ports.twilio)],
  ['TWILIO_API_BASE_URL', () => `http://127.0.0.1:${ports.twilio}`],
  ['TWILIO_ACCOUNT_SID', () => `AC${randomBytes(16).toString('hex')}`],
  ['TWILIO_AUTH_TOKEN', secret],
  ['TWILIO_FROM', () => '+15550001234'],
  ['TWILIO_CONTENT_SID', () => `HX${randomBytes(16).toString('hex')}`],
  ['TWILIO_STATUS_CALLBACK_URL', () => `http://127.0.0.1:${ports.api}/webhooks/verification/status`],
  ['DINER_CODE_SECRET', secret],
  ['PRIVACY_NOTICE_VERSION', () => 'dev'],
];

const line = ([name, value]) => `${name}=${value()}`;
const header = '# Generated by scripts/init-dev-env.mjs for local development and CI. Never for production.';

if (mode !== 'force' && existsSync(envPath)) {
  if (mode === 'create') {
    console.log(`${envPath} already exists; nothing to do (--update adds missing variables, --force replaces it).`);
    process.exit(0);
  }
  const present = new Set(
    readFileSync(envPath, 'utf8')
      .split('\n')
      .map((entry) => entry.split('=')[0].trim())
      .filter((name) => name.length > 0 && !name.startsWith('#')),
  );
  const missing = variables.filter(([name]) => !present.has(name));
  if (missing.length > 0) appendFileSync(envPath, `\n${missing.map(line).join('\n')}\n`);
  console.log(`Added ${missing.length} missing variable(s) to ${envPath}: ${missing.map(([name]) => name).join(', ') || 'none'}.`);
  process.exit(0);
}

writeFileSync(envPath, `${header}\n${variables.map(line).join('\n')}\n`, { mode: 0o600 });
console.log(`Wrote ${envPath} with new random development secrets.`);
