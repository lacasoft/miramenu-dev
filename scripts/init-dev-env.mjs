// Creates the root .env for local development and CI, with random secrets for the local
// containers. It never overwrites an existing .env unless --force is given, and it never
// prints the values. Production configuration comes from the platform, not from here.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const envPath = join(dirname(fileURLToPath(import.meta.url)), '..', '.env');
const force = process.argv.includes('--force');

if (existsSync(envPath) && !force) {
  console.log(`${envPath} already exists; nothing to do (use --force to replace it).`);
  process.exit(0);
}

const secret = () => randomBytes(24).toString('base64url');
const contexts = ['business_access', 'catalog', 'diners', 'interactions', 'measurement'];
const ports = { api: 3000, postgres: 55432, redis: 56379, s3: 58333, smtp: 51025, mailpitUi: 58025 };

const lines = [
  '# Generated by scripts/init-dev-env.mjs for local development and CI. Never for production.',
  `PORT=${ports.api}`,
  'CORS_ALLOWED_ORIGINS=',
  '',
  `POSTGRES_SUPERUSER_PASSWORD=${secret()}`,
  'DB_HOST=127.0.0.1',
  `DB_PORT=${ports.postgres}`,
  'DB_NAME=miramenu',
  'DB_MIGRATOR_USER=miramenu_migrator',
  `DB_MIGRATOR_PASSWORD=${secret()}`,
  ...contexts.flatMap((context) => [
    `DB_${context.toUpperCase()}_USER=miramenu_${context}`,
    `DB_${context.toUpperCase()}_PASSWORD=${secret()}`,
  ]),
  '',
  'REDIS_HOST=127.0.0.1',
  `REDIS_PORT=${ports.redis}`,
  `REDIS_PASSWORD=${secret()}`,
  '',
  `S3_PORT=${ports.s3}`,
  `S3_ENDPOINT=http://127.0.0.1:${ports.s3}`,
  'S3_REGION=us-east-1',
  'S3_BUCKET=media',
  `S3_ACCESS_KEY_ID=${randomBytes(12).toString('hex')}`,
  `S3_SECRET_ACCESS_KEY=${secret()}`,
  'S3_FORCE_PATH_STYLE=true',
  `MEDIA_PUBLIC_BASE_URL=http://127.0.0.1:${ports.s3}/media`,
  '',
  'SMTP_HOST=127.0.0.1',
  `SMTP_PORT=${ports.smtp}`,
  'SMTP_FROM="Miramenu <no-reply@miramenu.localhost>"',
  `MAILPIT_UI_PORT=${ports.mailpitUi}`,
  '',
];

writeFileSync(envPath, lines.join('\n'), { mode: 0o600 });
console.log(`Wrote ${envPath} with new random development secrets.`);
